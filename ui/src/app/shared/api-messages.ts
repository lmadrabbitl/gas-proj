const catalogs: Record<string, ApiMessageCatalog> = {
  'pt-BR': ptBrMessages,
};

let currentLanguage = DEFAULT_LANGUAGE;

export function setApiMessageLanguage(language: string): void {
  currentLanguage = catalogs[language] ? language : DEFAULT_LANGUAGE;
}

export function translateApiMessage(code: string | null | undefined): string | null {
  if (!code) {
    return null;
  }

  return catalogs[currentLanguage]?.[code] ?? null;
}
